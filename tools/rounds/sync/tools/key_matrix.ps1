# key_matrix.ps1 -- read-only key-by-key comparison of the user's official PCSX2 2.8.2 ini
# against our configuration, plus a *binary* recognition test: does each build's
# pcsx2-qt.exe / pcsx2-gsrunner.exe actually contain the setting key as a C string?
# A key that is absent from the binary that reads the ini is silently ignored by PCSX2
# (the compiled default wins), which is how "stale" keys are detected.
#
# usage: pwsh -File key_matrix.ps1
param(
  [string]$UserIni  = "$env:LOCALAPPDATA\PCSX2\inis\PCSX2.ini",
  [string]$OurIni   = "$env:USERPROFILE\Documents\PCSX2\inis\PCSX2.ini",
  [string]$UserExe  = "$env:LOCALAPPDATA\PCSX2\pcsx2-qt.exe",
  [string]$UserGsr  = "",   # official builds ship no gsrunner; empty = skip
  [string]$OurQtExe = "C:\Users\84363\Desktop\Ghost_Recon_2001_Locolization\work\builds\GR_HOOKEMU\qt\pcsx2-qt.exe",
  [string]$OurGsrExe= "C:\Users\84363\Desktop\Ghost_Recon_2001_Locolization\work\builds\GR_REPRO\emu\gsrunner\pcsx2-gsrunner.exe",
  [string]$OutCsv   = "C:\Users\84363\Desktop\Ghost_Recon_2001_Locolization\work\builds\GR_SYNC\A_key_matrix.csv",
  [string]$OutMd    = "C:\Users\84363\Desktop\Ghost_Recon_2001_Locolization\work\builds\GR_SYNC\A_key_matrix.md"
)
$ErrorActionPreference = 'Stop'

function Read-Ini([string]$path) {
  $sec = ''; $out = [ordered]@{}
  foreach ($line in [System.IO.File]::ReadAllLines($path)) {
    $l = $line.Trim()
    if ($l.Length -eq 0 -or $l.StartsWith(';') -or $l.StartsWith('#')) { continue }
    if ($l.StartsWith('[') -and $l.EndsWith(']')) { $sec = $l.Substring(1, $l.Length - 2); continue }
    $i = $l.IndexOf('=')
    if ($i -lt 0) { continue }
    $k = $l.Substring(0, $i).Trim(); $v = $l.Substring($i + 1).Trim()
    $full = "$sec/$k"
    if (-not $out.Contains($full)) { $out[$full] = $v }
  }
  return $out
}

# Binary key recognition: the key must appear as a NUL-terminated C string.
function Get-KeySet([string]$path) {
  if ([string]::IsNullOrEmpty($path) -or -not (Test-Path $path)) { return $null }
  $bytes = [System.IO.File]::ReadAllBytes((Resolve-Path $path))
  return [System.Text.Encoding]::ASCII.GetString($bytes)
}
function Test-Key([string]$blob, [string]$key) {
  if ($null -eq $blob) { return $null }   # n/a
  return $blob.Contains($key + [char]0)
}

$u  = Read-Ini $UserIni
$o  = Read-Ini $OurIni
$bu = Get-KeySet $UserExe
$bg = Get-KeySet $OurGsrExe
$bq = Get-KeySet $OurQtExe

$all = @($u.Keys) + @($o.Keys) | Sort-Object -Unique
$rows = foreach ($full in $all) {
  $slash = $full.LastIndexOf('/')
  $sec = $full.Substring(0, $slash); $key = $full.Substring($slash + 1)
  [pscustomobject]@{
    section        = $sec
    key            = $key
    user_value     = if ($u.Contains($full)) { $u[$full] } else { '<absent>' }
    our_ini_value  = if ($o.Contains($full)) { $o[$full] } else { '<absent>' }
    in_user_exe    = Test-Key $bu $key
    in_our_gsr_exe = Test-Key $bg $key
    in_our_qt_exe  = Test-Key $bq $key
    same           = ($u.Contains($full) -and $o.Contains($full) -and $u[$full] -ceq $o[$full])
  }
}
$rows | Export-Csv -Path $OutCsv -NoTypeInformation -Encoding UTF8

$diff = $rows | Where-Object { -not $_.same }
$dead = $diff | Where-Object { $_.in_user_exe -eq $false }

$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine("# A. key matrix (generated by tools/key_matrix.ps1)")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("- user ini : ``$UserIni``")
[void]$sb.AppendLine("- our ini  : ``$OurIni``")
[void]$sb.AppendLine("- user exe : ``$UserExe`` (in_user_exe = key present in the user's own binary)")
[void]$sb.AppendLine("- our gsr  : ``$OurGsrExe``")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("total keys=$($all.Count) differing=$($diff.Count) user-keys-ignored-by-user-exe=$($dead.Count)")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("| section | key | user | ours (Documents ini) | in user exe | in our gsrunner | note |")
[void]$sb.AppendLine("|---|---|---|---|---|---|---|")
foreach ($r in ($diff | Sort-Object section, key)) {
  $note = if ($r.in_user_exe -eq $false) { 'DEAD KEY: ignored by the user''s own build too' }
          elseif (-not $u.Contains("$($r.section)/$($r.key)")) { 'we-only key' }
          elseif (-not $o.Contains("$($r.section)/$($r.key)")) { 'user-only key' }
          else { '' }
  [void]$sb.AppendLine("| $($r.section) | $($r.key) | $($r.user_value) | $($r.our_ini_value) | $($r.in_user_exe) | $($r.in_our_gsr_exe) | $note |")
}
[System.IO.File]::WriteAllText($OutMd, $sb.ToString(), [System.Text.UTF8Encoding]::new($false))
Write-Output "wrote $OutMd and $OutCsv"
Write-Output "keys=$($all.Count) diff=$($diff.Count) dead=$($dead.Count)"
