import json, io, sys
sys.stdout.reconfigure(encoding='utf-8', errors='replace')
p = r'tools/font_pipeline/data/charset_compiled_zh16.json'
d = json.load(io.open(p, encoding='utf-8'))
print('mode =', d['mode'])
print('codes n =', len(d['codes']))
items = sorted(((int(v), k) for k, v in d['codes'].items()))
print('byte range:', hex(items[0][0]), '..', hex(items[-1][0]))
print('first 8:', items[:8])
print('last 8:', items[-8:])
used = set(b for b, _ in items)
print('E0..FF used:', ' '.join('%02X' % b for b in range(0xE0, 0x100) if b in used))
print('free in 0xB1..0xFF:', ' '.join('%02X' % b for b in range(0xB1, 0x100) if b not in used))
print('pair_of n =', len(d['pair_of']))
print('grid =', json.dumps(d['grid'], ensure_ascii=False)[:800])
print('mark_codes =', json.dumps(d['mark_codes'], ensure_ascii=False)[:600])
print('protected =', json.dumps(d['protected'], ensure_ascii=False)[:900])
print('trim19 =', d['trim19'], 'markers =', d['markers'])
print('_font_ext_zh93_fix keys =', list(d['_font_ext_zh93_fix'].keys())[:20])
print('_font_ext_planc_zh93 keys =', list(d['_font_ext_planc_zh93'].keys())[:20])
